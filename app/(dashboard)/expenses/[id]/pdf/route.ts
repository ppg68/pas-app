import { createClient } from "@/lib/supabase/server";
import { buildRequestPdf } from "@/lib/domain/requestPdf";
import { expenseSections } from "@/lib/domain/expenseSections";
import {
  STATUS_LABEL,
  money,
  type ExpenseApproval,
  type ExpenseFileRow,
  type ExpenseLineRow,
  type ExpenseReportRow,
} from "@/lib/domain/expenses";

export const dynamic = "force-dynamic";

export async function GET(_req: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return new Response("Not authenticated", { status: 401 });

  const { data } = await supabase.from("expense_reports").select("*").eq("id", id).maybeSingle();
  if (!data) return new Response("Expense report not found", { status: 404 });
  const r = data as ExpenseReportRow;
  const [{ data: ls }, { data: aps }, { data: fs }] = await Promise.all([
    supabase.from("expense_lines").select("*").eq("report_id", id),
    supabase.from("expense_approvals").select("*").eq("report_id", id),
    supabase.from("expense_files").select("*").eq("report_id", id),
  ]);
  const approvals = ((aps ?? []) as ExpenseApproval[]).sort((a, b) => (a.signer_role === "PM" ? -1 : 1) - (b.signer_role === "PM" ? -1 : 1));
  let tripNumber: string | null = null;
  if (r.trip_id) {
    const { data: t } = await supabase.from("trip_requests").select("number").eq("id", r.trip_id).maybeSingle();
    tripNumber = t?.number ?? null;
  }
  const s = expenseSections(r, (ls ?? []) as ExpenseLineRow[], approvals, (fs ?? []) as ExpenseFileRow[], tripNumber);

  const bytes = await buildRequestPdf(
    {
      title: `Expense report ${r.number}`,
      lines: [`${r.worker_name} - EUR ${money(r.total_eur)}`, `Status: ${STATUS_LABEL[r.status]}`],
      subtitle: r.subject,
      generated: `Generated by PAS on ${new Date().toLocaleString("it-IT", { timeZone: "Europe/Rome" })}`,
    },
    [s.header, ...s.lines, s.summary, s.history]
  );
  return new Response(new Uint8Array(bytes), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="Expense report ${r.number}.pdf"`,
    },
  });
}
